#endif

/* Emit the cspec package layout under <go_outdir>:
 *   internal/cspec/<P><pkg>_conv.c   converters + entry points + IOC tables
 *   internal/cspec/<prefix>.{c,h}    the asn1c-generated C copied from the
 *                                    -D dir (taken from ASN1CGO_DESTDIR —
 *                                    the driver hook budget is exhausted,
 *                                    so the destdir rides the same
 *                                    env-var channel ASN1C_PREFIX uses);
 *                                    only files starting with the run
 *                                    prefix are copied — the runtime set,
 *                                    pdu_collection.c and converter-
 *                                    example.c are unprefixed and drop out
 *                                    by that rule (prefix + layout rules)
 *   internal/cspec/cgo.go            the minimal cgo package file
 *   internal/cspec/rt headers        header-only rt copy (gated
 *                                    byte-identical to asn1cgo-rt's)
 * plus the asn1cgo-rt module skeleton at <go_outdir>/../asn1cgo-rt when
 * absent (fork skeletons .c subset + asn1cgo rt helpers + cgo.go, built
 * once; per-spec prefix and cspec layout) and <go_outdir>/go.mod's asn1cgo-rt require/replace.
 * Returns 0/-1. */
int go_conv_emit(const char *go_outdir, const char *go_rt_module);

#endif /* GO_CONV_H */
