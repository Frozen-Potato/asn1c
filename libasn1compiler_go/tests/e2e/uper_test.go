// UPER (X.691 unaligned PER) tests of the generated Go API: EncodeUPER /
// DecodeUPER<T> on fixed vectors worked out by hand, the error paths, a
// randomized round trip over every PDU type (APER -> UPER -> APER must give
// the same bytes, and the UPER bytes must equal the C converter's), and
// concurrent use. Copied into the generated module by tests/run-e2e.sh.
package e2e

import (
	"bytes"
	"errors"
	"math/rand"
	"os"
	"os/exec"
	"reflect"
	"strings"
	"sync"
	"testing"

	deep "asn1cgo.test/go/deep"
	ex "asn1cgo.test/go/synth_example"
	rt "github.com/Frozen-Potato/asn1c/libasn1compiler_go/rt/go/rt"
)

// uperDec maps a randPDUs name to its DecodeUPER<T>, and uperLabel to the
// ASN.1 type name (the C converter's -p argument); both filled by
// randreg_test.go (generated by run-e2e.sh).
var (
	uperDec   = map[string]func([]byte) (any, error){}
	uperLabel = map[string]string{}
)

type uperCodec interface {
	Encode() ([]byte, error)
	EncodeUPER() ([]byte, error)
}

func TestUPERKnownVector(t *testing.T) {
	in := &ex.ExamplePDU{
		RequestId: 7,
		Payload:   ex.ExamplePayload{Present: ex.ExamplePayloadPrNumber, Number: ptr(int64(42))},
		Note:      ptr("hi"),
	}
	// extension bit 0, note present 1, requestId 16 bits 7, payload:
	// extension bit 0, index 1, number 8 bits 42, note: length-1 in 5 bits
	// (1), 'h' 'i' in 7 bits each, then one 0 pad bit: 47 bits.
	want := []byte{0x40, 0x01, 0xd2, 0xa0, 0xe8, 0xd2}
	got, err := in.EncodeUPER()
	if err != nil {
		t.Fatalf("EncodeUPER: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("EncodeUPER = % x, want % x", got, want)
	}
	out, err := ex.DecodeUPERExamplePDU(want)
	if err != nil {
		t.Fatalf("DecodeUPER: %v", err)
	}
	if !reflect.DeepEqual(out, in) {
		t.Fatalf("DecodeUPER = %+v, want %+v", out, in)
	}

	// An extension alternative: extension bit 1, index 1 as a normally
	// small number (0 + 6 bits), then the open type: length 1, BOOLEAN
	// TRUE (1 bit, padded to an octet), no alignment anywhere.
	ec := &ex.ExtChoice{Present: ex.ExtChoicePrExtFlag, ExtFlag: ptr(true)}
	got, err = ec.EncodeUPER()
	if err != nil || !bytes.Equal(got, []byte{0x81, 0x01, 0x80}) {
		t.Fatalf("ExtChoice EncodeUPER = % x, %v; want 81 01 80", got, err)
	}
	ec2, err := ex.DecodeUPERExtChoice(got)
	if err != nil || !reflect.DeepEqual(ec2, ec) {
		t.Fatalf("ExtChoice DecodeUPER = %+v, %v", ec2, err)
	}

	// Flag-PDU (no extension marker): maybe absent 0, enabled 0, list
	// length 0 in 3 bits, sel: extension bit 0, index 0, flag 0: 8 bits.
	fp := &ex.FlagPDU{Flags: ex.FlagPDUFlags{}, Sel: ex.FlagChoice{Present: ex.FlagChoicePrFlag, Flag: ptr(ex.Flag(false))}}
	got, err = fp.EncodeUPER()
	if err != nil || !bytes.Equal(got, []byte{0x00}) {
		t.Fatalf("FlagPDU EncodeUPER = % x, %v; want 00", got, err)
	}
	// enabled 1, flags {TRUE, FALSE}, sel num 5: 0 1 010 1 0 0 1 101.
	fp = &ex.FlagPDU{Enabled: true, Flags: ex.FlagPDUFlags{true, false}, Sel: ex.FlagChoice{Present: ex.FlagChoicePrNum, Num: ptr(int64(5))}}
	got, err = fp.EncodeUPER()
	if err != nil || !bytes.Equal(got, []byte{0x54, 0xd0}) {
		t.Fatalf("FlagPDU EncodeUPER = % x, %v; want 54 d0", got, err)
	}
	if bal := rt.ArenaBalance(); bal != 0 {
		t.Fatalf("ArenaBalance = %d, want 0", bal)
	}
}

func decodeUPERErr(b []byte) error {
	_, err := ex.DecodeUPERExamplePDU(b)
	return err
}

func TestUPERErrors(t *testing.T) {
	wantErr(t, "DecodeUPER(nil)", decodeUPERErr(nil), rt.ErrArg)
	wantErr(t, "DecodeUPER(empty)", decodeUPERErr([]byte{}), rt.ErrArg)
	wantErr(t, "DecodeUPER(truncated)", decodeUPERErr([]byte{0x40, 0x01}), rt.ErrDecode)
	wantErr(t, "DecodeUPER(trailing)", decodeUPERErr([]byte{0x40, 0x01, 0xd2, 0xa0, 0xe8, 0xd2, 0x00}), rt.ErrTrailing)
	wantErr(t, "DecodeUPER(APER bytes)", decodeUPERErr([]byte{0x40, 0x00, 0x07, 0x40, 0x2a, 0x08, 0x68, 0x69}), rt.ErrDecode)
	var nilp *ex.ExamplePDU
	_, err := nilp.EncodeUPER()
	wantErr(t, "EncodeUPER(nil)", err, rt.ErrArg)
	_, err = (&ex.ExamplePDU{RequestId: 70000, Payload: ex.ExamplePayload{Present: ex.ExamplePayloadPrNumber, Number: ptr(int64(1))}}).EncodeUPER()
	wantErr(t, "EncodeUPER(out of range)", err, rt.ErrConstraint)
	_, err = (&ex.ExamplePDU{}).EncodeUPER()
	wantErr(t, "EncodeUPER(Present=0)", err, rt.ErrChoiceNothing)
	// The note's 5-bit length says 32 characters, the input ends first.
	wantErr(t, "DecodeUPER(short string)", decodeUPERErr([]byte{0x40, 0x01, 0xd2, 0xa0, 0xf8}), rt.ErrDecode)
	if bal := rt.ArenaBalance(); bal != 0 {
		t.Fatalf("ArenaBalance = %d, want 0", bal)
	}
}

// TestUPERIOC: the open-type values of an object set go through UPER too.
func TestUPERIOC(t *testing.T) {
	in := &deep.IOCMsg{Ies: deep.IOCMsgIes{deep.NewFieldIdA(5), deep.NewFieldIdB(1)}}
	u, err := in.EncodeUPER()
	if err != nil {
		t.Fatalf("EncodeUPER: %v", err)
	}
	a, err := in.Encode()
	if err != nil {
		t.Fatalf("Encode: %v", err)
	}
	out, err := deep.DecodeUPERIOCMsg(u)
	if err != nil {
		t.Fatalf("DecodeUPER(% x): %v", u, err)
	}
	if !reflect.DeepEqual(out, in) {
		t.Fatalf("DecodeUPER = %+v, want %+v", out, in)
	}
	if bin := os.Getenv("ASN1CGO_C_CONVERTER"); bin != "" {
		if c := convPDU(t, bin, "IOC-Msg", a, "-iaper", "-oper"); !bytes.Equal(c, u) {
			t.Fatalf("EncodeUPER = % x, C converter APER->UPER = % x", u, c)
		}
	}
}

// converterLabels: the PDU names the C converter knows exactly once (a name
// listed twice, from two modules, cannot be selected with -p).
func converterLabels(t *testing.T, bin string) map[string]bool {
	t.Helper()
	out, err := exec.Command(bin, "-p", "list").Output()
	if err != nil {
		t.Fatalf("converter -p list: %v", err)
	}
	n := map[string]int{}
	for _, l := range strings.Fields(string(out)) {
		n[l]++
	}
	once := map[string]bool{}
	for l, c := range n {
		if c == 1 {
			once[l] = true
		}
	}
	return once
}

// TestUPERRandomRoundTrip: for random values of every PDU type that Encode
// accepts, EncodeUPER must succeed, DecodeUPER<T> must read its output back,
// the decoded value must give the same APER bytes, and (with the C
// converter) the UPER bytes must equal the converter's APER -> UPER output.
func TestUPERRandomRoundTrip(t *testing.T) {
	if len(uperDec) == 0 || len(uperDec) != len(randPDUs) {
		t.Fatalf("uperDec has %d entries for %d PDU types: randreg_test.go was not generated", len(uperDec), len(randPDUs))
	}
	bin := os.Getenv("ASN1CGO_C_CONVERTER")
	var labels map[string]bool
	if bin != "" {
		labels = converterLabels(t, bin)
	}
	const iters = 90
	total, crossed := 0, 0
	for _, pdu := range randPDUs {
		dec := uperDec[pdu.name]
		for it := 0; it < iters; it++ {
			g := &randGen{rng: rand.New(rand.NewSource(int64(it) + 1)), mode: it % 3}
			p := reflect.New(pdu.typ)
			g.fill(p.Elem(), 0)
			v := p.Interface().(uperCodec)
			aper, err := v.Encode()
			if err != nil {
				continue // an invalid random value; Encode_test covers these
			}
			total++
			u, err := v.EncodeUPER()
			if err != nil {
				t.Errorf("%s it %d: EncodeUPER: %v (APER % x)", pdu.name, it, err, aper)
				break
			}
			d, err := dec(u)
			if err != nil {
				t.Errorf("%s it %d: DecodeUPER(% x): %v", pdu.name, it, u, err)
				break
			}
			aper2, err := d.(uperCodec).Encode()
			if err != nil || !bytes.Equal(aper, aper2) {
				t.Errorf("%s it %d: APER % x -> UPER % x -> APER % x (%v)", pdu.name, it, aper, u, aper2, err)
				break
			}
			// The C converter once per type and shape (it is a process).
			if lb := uperLabel[pdu.name]; bin != "" && it < 3 && labels[lb] {
				if c := convPDU(t, bin, lb, aper, "-iaper", "-oper"); !bytes.Equal(c, u) {
					t.Errorf("%s it %d: EncodeUPER = % x, C converter APER->UPER = % x", pdu.name, it, u, c)
					break
				}
				crossed++
			}
		}
	}
	if total < len(randPDUs) {
		t.Errorf("only %d values round-tripped for %d PDU types", total, len(randPDUs))
	}
	if bin != "" && crossed == 0 {
		t.Errorf("no value was cross-checked with the C converter")
	}
	t.Logf("%d values round-tripped, %d cross-checked with the C converter", total, crossed)
	if bal := rt.ArenaBalance(); bal != 0 {
		t.Fatalf("ArenaBalance = %d, want 0", bal)
	}
}

func TestUPERConcurrent(t *testing.T) {
	in := ex.ExamplePDU{
		RequestId: 9,
		Payload:   ex.ExamplePayload{Present: ex.ExamplePayloadPrText, Text: ptr("concurrent")},
	}
	u, err := in.EncodeUPER()
	if err != nil {
		t.Fatalf("EncodeUPER: %v", err)
	}
	const workers, iters = 16, 200
	var wg sync.WaitGroup
	errs := make(chan error, workers)
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := 0; i < iters; i++ {
				out, err := ex.DecodeUPERExamplePDU(u)
				if err != nil {
					errs <- err
					return
				}
				u2, err := out.EncodeUPER()
				if err != nil || !bytes.Equal(u, u2) {
					errs <- errors.New("UPER round trip mismatch")
					return
				}
			}
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		t.Error(err)
	}
	if bal := rt.ArenaBalance(); bal != 0 {
		t.Fatalf("ArenaBalance = %d after concurrent use, want 0", bal)
	}
}
